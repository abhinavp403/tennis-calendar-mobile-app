// Release signing credentials are read from local.properties (never committed) or, failing that,
// environment variables. The build stays functional for debug even when none are present.
val keystoreProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun secret(key: String): String? =
    keystoreProps.getProperty(key) ?: System.getenv(key)

